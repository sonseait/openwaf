import { useState } from "react";
import {
  Button,
  Group,
  NumberInput,
  Paper,
  Stack,
  Text,
  Textarea,
  rem,
} from "@mantine/core";
import {
  Controller,
  useFieldArray,
  useFormContext,
  useWatch,
} from "react-hook-form";
import { FileCode2, Plus } from "lucide-react";
import type { Document } from "../types";
import { Remove } from "./shared";

const sample = (status: number) => `<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Request could not be completed</title>
<style>
  body { margin: 0; padding: 12vh 1.5rem; background: #101a23; color: #ecf3f7; font: 1rem/1.6 system-ui, sans-serif; }
  main { max-width: 33.75rem; margin: auto; }
  .code { color: #78ddc5; font-size: 4.5rem; font-weight: 700; }
  h1 { font-size: 2rem; line-height: 1.2; }
  p { color: #adbeca; }
</style>
<main><div class="code">${status}</div><h1>Request could not be completed</h1>
<p>Contact the site administrator if you need help.</p></main>
</html>`;

export function ErrorPagesEditor({
  name = "error_pages",
}: {
  name?: "error_pages" | `routes.${number}.error_pages`;
}) {
  const { control } = useFormContext<Document>();
  const pages = useFieldArray({ control, name });
  const values = useWatch({ control, name });
  const [preview, setPreview] = useState<string | null>(null);
  const global = name === "error_pages";
  return (
    <Stack>
      <Text size="sm" c="dimmed">
        {global
          ? "Customize HTML for errors generated by this gateway, including unmatched routes."
          : "Override the global page for a specific status on this route. Other statuses inherit the global page."}{" "}
        Without a custom page, OpenWAF displays its built-in design. JSON API
        responses and upstream responses keep their original format.
      </Text>
      <Text size="xs" c="dimmed">
        Static HTML and inline CSS only. Scripts, forms, external assets and
        template variables are disabled. Maximum 16 pages per scope, 16 KiB per
        page; the whole configuration must fit in 64 KiB.
      </Text>
      {pages.fields.map((item, i) => (
        <Paper
          key={item.id}
          withBorder
          p="md"
          component="section"
          aria-label={`Custom error page ${i + 1}`}
        >
          <Stack>
            <Group justify="space-between" align="flex-start">
              <Controller
                control={control}
                name={`${name}.${i}.status`}
                rules={{
                  required: "Status is required",
                  min: 400,
                  max: 599,
                  validate: (value) =>
                    values?.filter((page) => page?.status === value).length ===
                      1 || "Use a unique status in this scope",
                }}
                render={({ field, fieldState }) => (
                  <NumberInput
                    {...field}
                    label="Error status"
                    min={400}
                    max={599}
                    allowDecimal={false}
                    allowNegative={false}
                    maw={rem(200)}
                    error={fieldState.error?.message}
                  />
                )}
              />
              <Remove
                label="Remove error page"
                onClick={() => pages.remove(i)}
              />
            </Group>
            <Controller
              control={control}
              name={`${name}.${i}.html`}
              rules={{
                validate: (value) => {
                  if (!value?.trim()) return "HTML is required";
                  if (value.includes("\0"))
                    return "HTML cannot contain null characters";
                  return (
                    new TextEncoder().encode(value).byteLength <= 16384 ||
                    "HTML exceeds 16 KiB"
                  );
                },
              }}
              render={({ field, fieldState }) => (
                <Textarea
                  {...field}
                  label="Error page HTML"
                  error={fieldState.error?.message}
                  autosize
                  minRows={8}
                  maxRows={18}
                  styles={{
                    input: {
                      fontFamily: "monospace",
                      fontSize: "var(--mantine-font-size-xs)",
                    },
                  }}
                />
              )}
            />
            <Group justify="space-between">
              <Text size="xs" c="dimmed">
                {new TextEncoder()
                  .encode(values?.[i]?.html ?? "")
                  .byteLength.toLocaleString()}{" "}
                / 16,384 bytes
              </Text>
              <Button
                variant="light"
                size="compact-xs"
                leftSection={<FileCode2 size={rem(14)} />}
                onClick={() => setPreview(preview === item.id ? null : item.id)}
              >
                {preview === item.id ? "Hide preview" : "Preview error page"}
              </Button>
            </Group>
            {preview === item.id && (
              <iframe
                title={`Error ${values?.[i]?.status ?? "page"} preview`}
                sandbox=""
                referrerPolicy="no-referrer"
                srcDoc={`<!doctype html><meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'">${values?.[i]?.html ?? ""}`}
                style={{
                  width: "100%",
                  height: rem(420),
                  border: "1px solid var(--mantine-color-default-border)",
                  borderRadius: "var(--mantine-radius-sm)",
                  background: "white",
                }}
              />
            )}
          </Stack>
        </Paper>
      ))}
      {!pages.fields.length && (
        <Text size="sm">
          {global
            ? "Using the OpenWAF default pages."
            : "Using global pages or the OpenWAF default pages."}
        </Text>
      )}
      <Button
        variant="light"
        leftSection={<Plus size={rem(16)} />}
        disabled={pages.fields.length >= 16}
        onClick={() => {
          const status =
            [
              503,
              403,
              404,
              429,
              502,
              504,
              ...Array.from({ length: 200 }, (_, i) => 400 + i),
            ].find(
              (status) => !values?.some((page) => page?.status === status),
            ) ?? 500;
          pages.append({
            status,
            html: sample(status),
          });
        }}
      >
        Add custom error page
      </Button>
    </Stack>
  );
}
